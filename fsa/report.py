"""Turns computed metrics and flags into an executive report.

Code computes every number; the LLM only writes the narrative around them and
is told not to introduce figures that are not in the input.
"""

from __future__ import annotations

import json
from dataclasses import asdict
from typing import Dict, List, Optional, Tuple

from .flags import Flag, evaluate
from .llm import LLMClient
from .ratios import YearMetrics, compute_year

SYSTEM = (
    "You are a senior financial analyst at an accounting firm. Write a concise executive "
    "summary for a business owner who is not a finance specialist. Use only the numbers "
    "provided. Never invent or recalculate figures. Structure: 1) Overall picture "
    "(2-3 sentences), 2) Main risks, 3) Recommended next steps (3 bullet points)."
)


def analyse(statements: Dict) -> Tuple[List[YearMetrics], List[Flag]]:
    years = sorted(statements["years"])
    metrics = [compute_year(y, statements["years"][y]) for y in years]
    prev: Optional[YearMetrics] = metrics[-2] if len(metrics) > 1 else None
    return metrics, evaluate(metrics[-1], prev)


def _fmt_money(v: float) -> str:
    return f"R$ {v:,.0f}".replace(",", ".")


def _fmt(v: Optional[float], kind: str) -> str:
    if v is None:
        return "n/a"
    return {"pct": f"{v * 100:.1f}%", "x": f"{v:.2f}x", "days": f"{v:.0f} days"}[kind]


ROWS = [
    ("Net revenue", "net_revenue", "money"),
    ("EBITDA", "ebitda", "money"),
    ("Net income", "net_income", "money"),
    ("Gross margin", "gross_margin", "pct"),
    ("EBITDA margin", "ebitda_margin", "pct"),
    ("Net margin", "net_margin", "pct"),
    ("Current ratio", "current_ratio", "x"),
    ("Quick ratio", "quick_ratio", "x"),
    ("Net debt / EBITDA", "net_debt_to_ebitda", "x"),
    ("Interest coverage", "interest_coverage", "x"),
    ("ROE", "roe", "pct"),
    ("Cash conversion cycle", "cash_conversion_cycle", "days"),
]


def metrics_table(metrics: List[YearMetrics]) -> str:
    head = "| Metric | " + " | ".join(m.year for m in metrics) + " |"
    sep = "|---|" + "---:|" * len(metrics)
    lines = [head, sep]
    for label, attr, kind in ROWS:
        vals = []
        for m in metrics:
            v = getattr(m, attr)
            vals.append(_fmt_money(v) if kind == "money" else _fmt(v, kind))
        lines.append(f"| {label} | " + " | ".join(vals) + " |")
    return "\n".join(lines)


def mock_summary(_system: str, prompt: str) -> str:
    """Deterministic narrative used in demo mode, built from the flags only."""
    payload = json.loads(prompt.split("DATA:", 1)[1])
    flags = payload["flags"]
    high = [f["message"] for f in flags if f["severity"] == "high"]
    medium = [f["message"] for f in flags if f["severity"] == "medium"]
    info = [f["message"] for f in flags if f["severity"] == "info"]
    out = ["**Overall picture.** " + (" ".join(info) or "Stable year.") +
           (" Several indicators need attention." if high else " No critical alerts.")]
    if high or medium:
        out.append("\n**Main risks**")
        out += [f"- {m}" for m in high + medium]
    out.append("\n**Recommended next steps**")
    out += [
        "- Review pricing and cost pass-through to recover margin.",
        "- Build a 13-week cash flow and renegotiate short-term debt maturities.",
        "- Set targets for receivable and inventory days and track them monthly.",
    ]
    out.append("\n_Demo mode: narrative generated by rules. Use --provider anthropic or openai for an AI-written summary._")
    return "\n".join(out)


def build_report(statements: Dict, client: LLMClient) -> str:
    metrics, flags = analyse(statements)
    payload = {
        "company": statements.get("company"),
        "metrics": [asdict(m) for m in metrics],
        "flags": [asdict(f) for f in flags],
    }
    prompt = "Write the executive summary for this company.\nDATA:" + json.dumps(payload)
    summary = client.complete(SYSTEM, prompt)

    flag_lines = [f"- **{f.severity.upper()}** · {f.area}: {f.message}" for f in flags] or ["- No alerts."]
    return "\n".join([
        f"# Financial analysis: {statements.get('company', 'Company')}",
        "",
        "## Key metrics",
        metrics_table(metrics),
        "",
        "## Alerts",
        *flag_lines,
        "",
        "## Executive summary",
        summary.strip(),
        "",
    ])
